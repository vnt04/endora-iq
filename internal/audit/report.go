// Report is the stable, serializable shape of an audit. It is marshaled to
// audit-report.json and is the single source rendered into audit-report.md.
//
// JSON schema (audit-report.json):
//
//	{
//	  "collection":     string,            // collection name
//	  "source":         string,            // "postman" | "openapi" | ...
//	  "endpoint_count": number,            // number of endpoints analyzed
//	  "coverage":       coverage.Result,   // {Overall, Categories[], MissingChecks[], RiskLevel}
//	  "quality":        scoring.Score,     // {Value, Grade, Subscores{...}}
//	  "missing_checks": [string],          // flat list of missing checks
//	  "risk_level":     string,            // "Low" | "Medium" | "High"
//	  "ai_analysis":    string,            // narrative or unavailable note (may be empty)
//	  "generated_by":   string             // tool + provider/model when AI used
//	}
type Report struct {
	Collection    string          `json:"collection"`
	Source        string          `json:"source"`
	EndpointCount int             `json:"endpoint_count"`
	Coverage      coverage.Result `json:"coverage"`
	Quality       scoring.Score   `json:"quality"`
	MissingChecks []string        `json:"missing_checks"`
	RiskLevel     string          `json:"risk_level"`
	AIAnalysis    string          `json:"ai_analysis"`
	GeneratedBy   string          `json:"generated_by"`
}

// buildReport assembles a Report from the parsed collection and computed scores.
func buildReport(c *core.Collection, cov coverage.Result, score scoring.Score, aiAnalysis string, cfg config.Config, aiUsed bool) Report {
	generatedBy := "apilens audit"
	if aiUsed {
		generatedBy = fmt.Sprintf("apilens audit (%s/%s)", cfg.Provider, cfg.Model)
	}

	name, source := "", ""
	if c != nil {
		name = c.Name
		source = string(c.Source)
	}

	return Report{
		Collection:    name,
		Source:        source,
		EndpointCount: c.EndpointCount(),
		Coverage:      cov,
		Quality:       score,
		MissingChecks: cov.MissingChecks,
		RiskLevel:     riskLevelOf(cov, score),
		AIAnalysis:    aiAnalysis,
		GeneratedBy:   generatedBy,
	}
}

// renderJSON marshals the report as indented JSON with a trailing newline.
func renderJSON(r Report) ([]byte, error) {
	data, err := json.MarshalIndent(r, "", "  ")
	if err != nil {
		return nil, fmt.Errorf("marshal audit report: %w", err)
	}
	return append(data, '\n'), nil
}

// renderMarkdown renders the report as clean Markdown following the SRS §10
// layout: title, scores, per-category coverage table, missing-checks list,
// risk level, and the AI analysis section.
func renderMarkdown(r Report) string {
	var b strings.Builder

	b.WriteString("# ApiLens Audit Report\n\n")
	fmt.Fprintf(&b, "**Collection:** %s  \n", orDash(r.Collection))
	fmt.Fprintf(&b, "**Source:** %s  \n", orDash(r.Source))
	fmt.Fprintf(&b, "**Endpoints:** %d  \n", r.EndpointCount)
	fmt.Fprintf(&b, "**Generated by:** %s\n\n", orDash(r.GeneratedBy))

	b.WriteString("## Scores\n\n")
	fmt.Fprintf(&b, "- **Coverage Score:** %d / 100\n", r.Coverage.Overall)
	fmt.Fprintf(&b, "- **Quality Score:** %d / 100 (Grade %s)\n", r.Quality.Value, orDash(r.Quality.Grade))
	fmt.Fprintf(&b, "- **Risk Level:** %s\n\n", orDash(r.RiskLevel))

	writeSubscores(&b, r.Quality.Subscores)
	writeCategories(&b, r.Coverage.Categories)
	writeMissing(&b, r.MissingChecks)
	writeAnalysis(&b, r.AIAnalysis)

	return b.String()
}

// writeSubscores renders the quality subscore breakdown.
func writeSubscores(b *strings.Builder, s scoring.Subscores) {
	b.WriteString("## Quality Subscores\n\n")
	b.WriteString("| Dimension | Score |\n|-----------|------:|\n")
	fmt.Fprintf(b, "| Coverage | %d |\n", s.Coverage)
	fmt.Fprintf(b, "| Validation | %d |\n", s.Validation)
	fmt.Fprintf(b, "| Security | %d |\n", s.Security)
	fmt.Fprintf(b, "| Error Handling | %d |\n", s.ErrorHandling)
	fmt.Fprintf(b, "| Documentation | %d |\n\n", s.Documentation)
}

// writeCategories renders the per-category coverage table.
func writeCategories(b *strings.Builder, cats []coverage.CategoryScore) {
	b.WriteString("## Coverage by Category\n\n")
	if len(cats) == 0 {
		b.WriteString("_No category data available._\n\n")
		return
	}
	b.WriteString("| Category | Score | Found | Missing |\n|----------|------:|------:|--------:|\n")
	for _, c := range cats {
		fmt.Fprintf(b, "| %s | %d | %d | %d |\n", orDash(c.Name), c.Score, len(c.Found), len(c.Missing))
	}
	b.WriteString("\n")
}

// writeMissing renders the flat missing-checks bullet list.
func writeMissing(b *strings.Builder, missing []string) {
	b.WriteString("## Missing\n\n")
	if len(missing) == 0 {
		b.WriteString("- None\n\n")
		return
	}
	for _, m := range missing {
		fmt.Fprintf(b, "- %s\n", m)
	}
	b.WriteString("\n")
}

// writeAnalysis renders the AI narrative section, falling back to the
// unavailable note when no narrative is present.
func writeAnalysis(b *strings.Builder, analysis string) {
	b.WriteString("## AI Analysis\n\n")
	body := strings.TrimSpace(analysis)
	if body == "" {
		body = unavailableNote
	}
	b.WriteString(body)
	b.WriteString("\n")
}

// categoryScore returns the score for the coverage category whose name matches
// target (case-insensitive, prefix-tolerant), or 0 when absent.
func categoryScore(cov coverage.Result, target string) int {
	want := strings.ToLower(strings.TrimSpace(target))
	for _, cat := range cov.Categories {
		got := strings.ToLower(strings.TrimSpace(cat.Name))
		if got == want || strings.HasPrefix(got, want) {
			return cat.Score
		}
	}
	return 0
}

// documentationScore is the deterministic share of endpoints carrying a
// non-empty Description, scaled to 0-100. With no endpoints it is 0.
func documentationScore(c *core.Collection) int {
	if c == nil || len(c.Endpoints) == 0 {
		return 0
	}
	documented := 0
	for _, e := range c.Endpoints {
		if strings.TrimSpace(e.Description) != "" {
			documented++
		}
	}
	total := len(c.Endpoints)
	// Integer rounding: (documented*100 + total/2) / total.
	return (documented*100 + total/2) / total
}

// riskLevelOf prefers the coverage engine's risk level and falls back to a
// quality-score-derived band when the engine left it unset.
func riskLevelOf(cov coverage.Result, score scoring.Score) string {
	if rl := strings.TrimSpace(cov.RiskLevel); rl != "" {
		return rl
	}
	switch {
	case score.Value >= 80:
		return "Low"
	case score.Value >= 60:
		return "Medium"
	default:
		return "High"
	}
}

// orDash returns s, or "-" when s is blank, for tidy rendering.
func orDash(s string) string {
	if strings.TrimSpace(s) == "" {
		return "-"
	}
	return s
}
