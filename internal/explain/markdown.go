package explain

import (
	"fmt"
	"strings"

	"github.com/apilens/apilens/internal/core"
	"github.com/apilens/apilens/internal/core/redact"
)

// buildMarkdown renders the full failure-analysis report: a run summary, a
// failure-group overview table, and one detailed section per group (with the AI
// analysis, or a deterministic-only note). analyses is index-aligned to groups.
func buildMarkdown(report *core.NewmanReport, groups []failureGroup, analyses []string, aiAvailable bool) string {
	var b strings.Builder
	writeHeader(&b, report)

	if !aiAvailable {
		b.WriteString("> **Note:** AI analysis is unavailable (no provider/API key configured). ")
		b.WriteString("The grouping below is deterministic; configure a provider for root-cause predictions.\n\n")
	}

	if len(groups) == 0 {
		b.WriteString("## Failures\n\n")
		b.WriteString(fmt.Sprintf(
			"This run reported %d failed assertion(s), but no per-assertion detail was available to group. "+
				"Re-run newman with the JSON reporter to capture assertion errors.\n", report.Failed))
		return b.String()
	}

	writeGroupTable(&b, groups)
	b.WriteString("---\n\n")
	for i, g := range groups {
		writeGroup(&b, i+1, g, analyses[i])
	}
	return b.String()
}

// buildAllPassedMarkdown renders the clean report for a run with no failures.
func buildAllPassedMarkdown(report *core.NewmanReport) string {
	var b strings.Builder
	writeHeader(&b, report)
	b.WriteString("## All tests passed\n\n")
	b.WriteString(fmt.Sprintf(
		"No failed assertions were found across %d assertion(s) in this run. No failure analysis is necessary.\n",
		report.Total))
	return b.String()
}

// writeHeader writes the title and run-summary block.
func writeHeader(b *strings.Builder, report *core.NewmanReport) {
	name := strings.TrimSpace(report.CollectionName)
	if name == "" {
		name = "(unnamed collection)"
	}
	b.WriteString("# API Failure Analysis\n\n")
	b.WriteString("_Generated by ApiLens._\n\n")
	b.WriteString("## Summary\n\n")
	b.WriteString(fmt.Sprintf("- **Collection:** %s\n", mdInline(name)))
	b.WriteString(fmt.Sprintf("- **Total assertions:** %d\n", report.Total))
	b.WriteString(fmt.Sprintf("- **Passed:** %d\n", report.Passed))
	b.WriteString(fmt.Sprintf("- **Failed:** %d\n\n", report.Failed))
}

// writeGroupTable writes the overview table of failure groups.
func writeGroupTable(b *strings.Builder, groups []failureGroup) {
	b.WriteString("## Failure Groups\n\n")
	b.WriteString("| # | Error Type | Failures | Endpoints |\n")
	b.WriteString("|---|------------|----------|-----------|\n")
	for i, g := range groups {
		b.WriteString(fmt.Sprintf("| %d | %s | %d | %d |\n",
			i+1, mdCell(errorNameOrUnknown(g.ErrorName)), g.Count, len(g.Endpoints)))
	}
	b.WriteString("\n")
}

// writeGroup writes one detailed group section: deterministic facts followed by
// the AI analysis (or note).
func writeGroup(b *strings.Builder, n int, g failureGroup, analysis string) {
	b.WriteString(fmt.Sprintf("## Group %d: %s\n\n", n, mdInline(errorNameOrUnknown(g.ErrorName))))
	b.WriteString(fmt.Sprintf("**Failures:** %d\n\n", g.Count))

	if len(g.Endpoints) > 0 {
		b.WriteString("**Affected endpoints:**\n\n")
		for _, e := range g.Endpoints {
			b.WriteString(fmt.Sprintf("- `%s`\n", redact.String(e)))
		}
		b.WriteString("\n")
	}

	if len(g.Assertions) > 0 {
		b.WriteString("**Failed assertions:**\n\n")
		for _, a := range g.Assertions {
			b.WriteString(fmt.Sprintf("- %s\n", mdInline(redact.String(a))))
		}
		b.WriteString("\n")
	}

	if msg := strings.TrimSpace(g.SampleMessage); msg != "" {
		b.WriteString("**Representative error message:**\n\n")
		b.WriteString("```\n")
		b.WriteString(redact.String(msg))
		b.WriteString("\n```\n\n")
	}

	b.WriteString("### AI Analysis\n\n")
	if strings.TrimSpace(analysis) == "" {
		analysis = noteAIUnavailable
	}
	b.WriteString(analysis)
	b.WriteString("\n\n---\n\n")
}

// errorNameOrUnknown returns a display name for an error, defaulting to a label
// for unnamed/blank assertion errors.
func errorNameOrUnknown(name string) string {
	if n := strings.TrimSpace(name); n != "" {
		return n
	}
	return "Failed assertion"
}

// mdInline flattens text to a single line for inline use.
func mdInline(s string) string {
	return strings.TrimSpace(oneLine(s))
}

// mdCell flattens text and escapes table-breaking pipe characters.
func mdCell(s string) string {
	return strings.ReplaceAll(mdInline(s), "|", "\\|")
}

// oneLine collapses all whitespace runs (including newlines/tabs) to single
// spaces.
func oneLine(s string) string {
	return strings.Join(strings.Fields(s), " ")
}

// truncate shortens s to at most n runes, appending an ellipsis when cut.
func truncate(s string, n int) string {
	r := []rune(s)
	if len(r) <= n {
		return s
	}
	if n <= 3 {
		return string(r[:n])
	}
	return string(r[:n-3]) + "..."
}
