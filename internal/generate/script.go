package generate

import (
	"bytes"
	"encoding/json"
	"fmt"
	"regexp"
	"strings"
)

// fenceLine matches a markdown code-fence line on its own, optionally tagged
// with a language hint (```js, ```javascript) or a closing ``` line.
var fenceLine = regexp.MustCompile("(?m)^\\s*`{3,}[a-zA-Z0-9]*\\s*$")

// stripFences removes markdown code-fence lines (```js ... ```), keeping the
// code between them. Fence lines anywhere in the text are dropped, which also
// handles models that wrap output in a single block or emit a stray closing
// fence. The result is whitespace-trimmed.
func stripFences(s string) string {
	if s == "" {
		return ""
	}
	cleaned := fenceLine.ReplaceAllString(s, "")
	return strings.TrimSpace(cleaned)
}

// withHeader prepends a stable header comment so the output always begins with
// a comment identifying its origin and target endpoint.
func withHeader(body, method, path string, status int) string {
	header := fmt.Sprintf(`// Generated by ApiLens — AI Test Generator (SRS Feature A)
// Endpoint: %s %s
// Expected status: %d
// Runnable in the Postman Tests tab and Newman. Regenerate with: apilens generate
`, method, path, status)
	return header + "\n" + body + "\n"
}

// normalizeJSON pretty-prints raw when it is valid JSON; otherwise it returns
// the trimmed raw bytes unchanged so non-JSON example bodies still flow through.
func normalizeJSON(raw []byte) string {
	trimmed := bytes.TrimSpace(raw)
	if len(trimmed) == 0 {
		return ""
	}
	var v any
	if err := json.Unmarshal(trimmed, &v); err != nil {
		return string(trimmed)
	}
	pretty, err := json.MarshalIndent(v, "", "  ")
	if err != nil {
		return string(trimmed)
	}
	return string(pretty)
}
